-- Perfiles asociados a los usuarios de Supabase Auth.
create table if not exists public.perfiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  nombre text not null default '',
  apellido text not null default '',
  rol text not null default 'profesor'
    check (rol in ('profesor', 'administracion')),
  materia text not null default 'matematica',
  curso text not null default '',
  descripcion text not null default '',
  foto text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.perfiles enable row level security;

grant select, insert, update on public.perfiles to authenticated;

drop policy if exists "perfiles_select_propios" on public.perfiles;
create policy "perfiles_select_propios"
on public.perfiles for select
to authenticated
using ((select auth.uid()) = id);

drop policy if exists "perfiles_insert_propio" on public.perfiles;
create policy "perfiles_insert_propio"
on public.perfiles for insert
to authenticated
with check ((select auth.uid()) = id);

drop policy if exists "perfiles_update_propio" on public.perfiles;
create policy "perfiles_update_propio"
on public.perfiles for update
to authenticated
using ((select auth.uid()) = id)
with check ((select auth.uid()) = id);

create or replace function public.crear_perfil_usuario()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.perfiles (id, email, nombre, apellido, rol)
  values (
    new.id,
    coalesce(new.email, ''),
    coalesce(new.raw_user_meta_data ->> 'nombre', ''),
    coalesce(new.raw_user_meta_data ->> 'apellido', ''),
    case
      when coalesce(new.raw_user_meta_data ->> 'rol', 'profesor')
        in ('profesor', 'administracion')
      then coalesce(new.raw_user_meta_data ->> 'rol', 'profesor')
      else 'profesor'
    end
  )
  on conflict (id) do nothing;

  return new;
end;
$$;

drop trigger if exists crear_perfil_al_registrar_usuario on auth.users;
create trigger crear_perfil_al_registrar_usuario
after insert on auth.users
for each row execute procedure public.crear_perfil_usuario();

-- Tabla principal de tutorías.
create table if not exists public.tutorias (
  id bigint generated by default as identity primary key,
  materia text not null,
  curso text not null,
  dia text not null,
  horario text not null,
  estudiante text not null,
  email text,
  whatsapp text,
  creador_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public.tutorias
  add column if not exists creador_id uuid references auth.users(id) on delete set null;

create index if not exists tutorias_creador_id_idx
  on public.tutorias (creador_id);

alter table public.tutorias enable row level security;

grant select, insert on public.tutorias to anon, authenticated;

drop policy if exists "tutorias_select_public" on public.tutorias;
create policy "tutorias_select_public"
on public.tutorias for select
to anon, authenticated
using (true);

drop policy if exists "tutorias_insert_public" on public.tutorias;
create policy "tutorias_insert_public"
on public.tutorias for insert
to anon, authenticated
with check (true);
